using System;
using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace LANCommander.Interposer.Events
{
    /// <summary>Which step of a match a <see cref="MatchReportedEventArgs"/> describes.</summary>
    public enum MatchReportKind
    {
        /// <summary>A match started (InterposerMatchStart).</summary>
        Start,

        /// <summary>A player joined, left, or changed name or team.</summary>
        Participant,

        /// <summary>Something happened in the match.</summary>
        Event,

        /// <summary>The match ended, with its standings and totals.</summary>
        End,

        /// <summary>A file was attached to the match.</summary>
        Attach,
    }

    /// <summary>
    /// A match as it started. The JSON is shaped like LANCommander's <c>MatchCreateRequest</c>, so it can
    /// be deserialized straight into one; <see cref="GameId"/> is only set when the game's Config.yml
    /// names it, and is otherwise for the launcher to fill in.
    /// </summary>
    public sealed class MatchStart
    {
        /// <summary>LANCommander's id for the game, when Config.yml names one.</summary>
        [JsonPropertyName("gameId")] public string? GameId { get; init; }
        /// <summary>LANCommander's id for the game server, when Config.yml names one.</summary>
        [JsonPropertyName("serverId")] public string? ServerId { get; init; }
        /// <summary>The game's own id for the match.</summary>
        [JsonPropertyName("externalId")] public string ExternalId { get; init; } = string.Empty;
        /// <summary>The map played.</summary>
        [JsonPropertyName("map")] public string? Map { get; init; }
        /// <summary>The game mode played.</summary>
        [JsonPropertyName("mode")] public string? Mode { get; init; }
        /// <summary>The game's version.</summary>
        [JsonPropertyName("gameVersion")] public string? GameVersion { get; init; }
        /// <summary>For a server LANCommander does not manage: its name.</summary>
        [JsonPropertyName("serverName")] public string? ServerName { get; init; }
        /// <summary>For a server LANCommander does not manage: the address players connect to.</summary>
        [JsonPropertyName("serverAddress")] public string? ServerAddress { get; init; }
        /// <summary>When the match started, UTC.</summary>
        [JsonPropertyName("startedOn")] public DateTime StartedOn { get; init; }
        /// <summary>The rules the match is played with, as a JSON object.</summary>
        [JsonPropertyName("settings")] public JsonElement? Settings { get; init; }
        /// <summary>Anything else kept with the match, as a JSON object.</summary>
        [JsonPropertyName("metadata")] public JsonElement? Metadata { get; init; }

        /// <summary><c>Server</c>, <c>Host</c> or <c>Client</c>, from MatchStatistics.ReporterKind.</summary>
        [JsonPropertyName("reporterKind")] public string ReporterKind { get; init; } = "Server";

        /// <summary>A name to tell reporters apart, such as the host name.</summary>
        [JsonPropertyName("reporterName")] public string? ReporterName { get; init; }

        /// <summary>
        /// True when the launcher is the one to report the match: the DLL has no LANCommander server
        /// configured and is not sending it itself. A launcher must ignore a match with this false, or it
        /// would be reported twice.
        /// </summary>
        [JsonPropertyName("forward")] public bool Forward { get; init; }
    }

    /// <summary>A player in a match, shaped like LANCommander's <c>MatchParticipantSubmission</c>.</summary>
    public sealed class MatchParticipant
    {
        /// <summary>The player, by player key: <c>steam:STEAM_0:1:123</c>, <c>name:Pat</c>.</summary>
        [JsonPropertyName("playerKey")] public string PlayerKey { get; init; } = string.Empty;
        /// <summary>The name the player plays under.</summary>
        [JsonPropertyName("displayName")] public string? DisplayName { get; init; }
        /// <summary>The team.</summary>
        [JsonPropertyName("team")] public string? Team { get; init; }
        /// <summary>Game time the player joined, in milliseconds.</summary>
        [JsonPropertyName("joinedAtMilliseconds")] public long? JoinedAtMilliseconds { get; init; }
        /// <summary>Game time the player left, in milliseconds.</summary>
        [JsonPropertyName("leftAtMilliseconds")] public long? LeftAtMilliseconds { get; init; }
    }

    /// <summary>One thing that happened, shaped like LANCommander's <c>MatchEventSubmission</c>.</summary>
    public sealed class MatchEvent
    {
        /// <summary>Generated by the DLL when the event was recorded.</summary>
        [JsonPropertyName("id")] public Guid Id { get; init; }

        /// <summary>The DLL's numbering; a reporter that renumbers (MatchRecorder does) may ignore it.</summary>
        [JsonPropertyName("sequence")] public long Sequence { get; init; }

        /// <summary>What happened, lowercase with underscores: <c>kill</c>, <c>lap_completed</c>.</summary>
        [JsonPropertyName("type")] public string Type { get; init; } = string.Empty;
        /// <summary>Milliseconds of game time since the match started.</summary>
        [JsonPropertyName("gameTimeMilliseconds")] public long GameTimeMilliseconds { get; init; }
        /// <summary>The game's simulation tick, when it has one.</summary>
        [JsonPropertyName("tick")] public long? Tick { get; init; }
        /// <summary>The player key of who caused the event, if anyone.</summary>
        [JsonPropertyName("actorKey")] public string? ActorKey { get; init; }
        /// <summary>The player key of who it happened to, if anyone.</summary>
        [JsonPropertyName("subjectKey")] public string? SubjectKey { get; init; }
        /// <summary>The detail, as a JSON object.</summary>
        [JsonPropertyName("payload")] public JsonElement? Payload { get; init; }
        /// <summary>The game's clock when it happened, UTC.</summary>
        [JsonPropertyName("clientTime")] public DateTime? ClientTime { get; init; }
    }

    /// <summary>A place in the final standings, shaped like LANCommander's <c>MatchResultSubmission</c>.</summary>
    public sealed class MatchResult
    {
        /// <summary>The player, by player key: <c>steam:STEAM_0:1:123</c>, <c>name:Pat</c>.</summary>
        [JsonPropertyName("playerKey")] public string? PlayerKey { get; init; }
        /// <summary>The team.</summary>
        [JsonPropertyName("team")] public string? Team { get; init; }
        /// <summary>1 for the winner; tied entries share a rank.</summary>
        [JsonPropertyName("rank")] public int Rank { get; init; }
        /// <summary>The score, when the game keeps one.</summary>
        [JsonPropertyName("score")] public double? Score { get; init; }

        /// <summary><c>Finished</c>, <c>DidNotFinish</c>, <c>Disqualified</c>, <c>Defeated</c> or <c>Forfeited</c>.</summary>
        [JsonPropertyName("status")] public string Status { get; init; } = "Finished";

        /// <summary>A finishing time in milliseconds, for races.</summary>
        [JsonPropertyName("timeMilliseconds")] public long? TimeMilliseconds { get; init; }
        /// <summary>The detail, as a JSON object.</summary>
        [JsonPropertyName("payload")] public JsonElement? Payload { get; init; }
    }

    /// <summary>An end-of-match total, shaped like LANCommander's <c>MatchStatisticSubmission</c>.</summary>
    public sealed class MatchStatistic
    {
        /// <summary>The player, by player key: <c>steam:STEAM_0:1:123</c>, <c>name:Pat</c>.</summary>
        [JsonPropertyName("playerKey")] public string? PlayerKey { get; init; }
        /// <summary>The team.</summary>
        [JsonPropertyName("team")] public string? Team { get; init; }
        /// <summary>What was counted, lowercase with underscores: <c>kills</c>, <c>best_lap_ms</c>.</summary>
        [JsonPropertyName("key")] public string Key { get; init; } = string.Empty;
        /// <summary>The total.</summary>
        [JsonPropertyName("value")] public double Value { get; init; }
    }

    /// <summary>The end of a match, shaped like LANCommander's <c>MatchEndRequest</c>.</summary>
    public sealed class MatchEnd
    {
        /// <summary>When the match ended, UTC.</summary>
        [JsonPropertyName("endedOn")] public DateTime EndedOn { get; init; }
        /// <summary>Why it ended: <c>completed</c>, <c>time_limit</c>, <c>aborted</c>.</summary>
        [JsonPropertyName("reason")] public string? Reason { get; init; }
        /// <summary>The match was cut short and its results should not count.</summary>
        [JsonPropertyName("abandoned")] public bool Abandoned { get; init; }
        /// <summary>The final standings.</summary>
        [JsonPropertyName("results")] public List<MatchResult> Results { get; init; } = new();
        /// <summary>The end-of-match totals.</summary>
        [JsonPropertyName("statistics")] public List<MatchStatistic> Statistics { get; init; } = new();
    }

    /// <summary>A file attached to a match, to be uploaded by whoever reports it.</summary>
    public sealed class MatchAttachment
    {
        /// <summary>The file's full path in the game's file system.</summary>
        [JsonPropertyName("path")] public string Path { get; init; } = string.Empty;

        /// <summary><c>Demo</c>, <c>Replay</c>, <c>Log</c>, <c>Screenshot</c> or <c>Other</c>.</summary>
        [JsonPropertyName("kind")] public string Kind { get; init; } = "Other";

        /// <summary>The file's name.</summary>
        [JsonPropertyName("fileName")] public string FileName { get; init; } = string.Empty;
        /// <summary>The file's media type.</summary>
        [JsonPropertyName("contentType")] public string ContentType { get; init; } = "application/octet-stream";
        /// <summary>The file's size in bytes when it was attached.</summary>
        [JsonPropertyName("size")] public long Size { get; init; }
        /// <summary>Game time where the file starts, in milliseconds.</summary>
        [JsonPropertyName("startMilliseconds")] public long? StartMilliseconds { get; init; }
        /// <summary>Game time where the file ends, in milliseconds.</summary>
        [JsonPropertyName("endMilliseconds")] public long? EndMilliseconds { get; init; }
    }

    /// <summary>
    /// One step of a match the game reported through the InterposerMatch* API. Every step of every
    /// match is raised, whoever delivers it; <see cref="MatchStart.Forward"/> says whether the launcher
    /// is the one expected to.
    /// </summary>
    public sealed class MatchReportedEventArgs : EventArgs
    {
        /// <summary>What happened.</summary>
        public MatchReportKind Kind { get; }

        /// <summary>The DLL's handle for the match: the same for every step of one match.</summary>
        public uint Match { get; }

        /// <summary>The step as the DLL sent it (see MatchStatistics.md).</summary>
        public string Json { get; }

        internal MatchReportedEventArgs(MatchReportKind kind, uint match, string json)
        {
            Kind  = kind;
            Match = match;
            Json  = json;
        }

        /// <summary>The start, when <see cref="Kind"/> is <see cref="MatchReportKind.Start"/>.</summary>
        public MatchStart? Start => Kind == MatchReportKind.Start ? Read<MatchStart>() : null;

        /// <summary>The player, when <see cref="Kind"/> is <see cref="MatchReportKind.Participant"/>.</summary>
        public MatchParticipant? Participant => Kind == MatchReportKind.Participant ? Read<MatchParticipant>() : null;

        /// <summary>The event, when <see cref="Kind"/> is <see cref="MatchReportKind.Event"/>.</summary>
        public MatchEvent? Event => Kind == MatchReportKind.Event ? Read<MatchEvent>() : null;

        /// <summary>The end, when <see cref="Kind"/> is <see cref="MatchReportKind.End"/>.</summary>
        public MatchEnd? End => Kind == MatchReportKind.End ? Read<MatchEnd>() : null;

        /// <summary>The file, when <see cref="Kind"/> is <see cref="MatchReportKind.Attach"/>.</summary>
        public MatchAttachment? Attachment => Kind == MatchReportKind.Attach ? Read<MatchAttachment>() : null;

        internal static MatchReportKind? ParseKind(string? kind) => kind switch
        {
            "START"       => MatchReportKind.Start,
            "PARTICIPANT" => MatchReportKind.Participant,
            "EVENT"       => MatchReportKind.Event,
            "END"         => MatchReportKind.End,
            "ATTACH"      => MatchReportKind.Attach,
            _             => null,
        };

        private T? Read<T>() where T : class
        {
            try
            {
                return JsonSerializer.Deserialize<T>(Json);
            }
            catch (JsonException)
            {
                return null;
            }
        }
    }
}
